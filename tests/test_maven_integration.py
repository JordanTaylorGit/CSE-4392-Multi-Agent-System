"""Real Maven/JaCoCo E2E on a tiny fixture; it is not assignment-run evidence."""
import json
import shutil
from pathlib import Path

import pytest
from langchain_core.messages import AIMessage
from langchain_core.runnables import RunnableLambda
from langgraph.checkpoint.sqlite import SqliteSaver
from langgraph.types import Command

from harness.cli import drive
from harness.graph import build_graph
from harness.workspace import RunWorkspace, write_json

ROOT = Path(__file__).resolve().parents[1]


@pytest.mark.skipif(not shutil.which("mvn"), reason="Maven and JDK 17 are required")
def test_real_maven_pipeline_produces_two_verified_coverage_reports(tmp_path):
    run = RunWorkspace.create(ROOT, tmp_path / "fixture-run", "seasonswitch")
    shutil.rmtree(run.workspace / "java/src")
    source = run.workspace / "java/src/original/java/fixture/Sample.java"
    source.parent.mkdir(parents=True)
    source.write_text('package fixture; public class Sample { '
                      'public int sign(int n) { if(n < 0) return -1; return 1; } }')
    profile = {**run.profile, "subject": "Sample", "source": str(source.relative_to(run.workspace)),
               "test_root": "java/src/test/java/fixture", "units": [{"name": "sign", "params": ["n"]}],
               "boundaries": [{"value": 0}], "observable": ["return"], "constraints": []}
    write_json(run.profile_path, profile)
    run = RunWorkspace(run.directory)
    # A deliberately small, deterministic project adapter used only inside this test's workspace.
    (run.profile_path.parent / "junit_adapter.py").write_text('''
def render(cases, profile, class_name):
    source = "// Generated by P4 testgen Phase C; do not edit by hand.\\npackage fixture;\\n"
    source += "import org.junit.jupiter.api.Test; import static org.junit.jupiter.api.Assertions.*;\\n"
    source += "class " + class_name + " {\\n"
    for i, case in enumerate(cases):
        source += "@Test void test" + str(i) + "() { assertEquals(" + str(case['expected']['return'])
        source += ", new Sample().sign(" + str(case['inputs']['n']) + ")); }\\n"
    return source + "}\\n"
''')

    def respond(messages):
        stage = json.loads(messages[1].content)["stage"]
        if stage in {"ep", "bva"}:
            method = stage.upper()
            result = {"generated_by": stage, "target": "original", "cases": [{
                "id": f"{method}-01", "method": method, "target": "original", "unit": "sign",
                "setup": {}, "inputs": {"n": -1 if stage == "ep" else 0},
                "expected": {"return": -1 if stage == "ep" else 1},
                "partition": "fixture", "rationale": "Known boundary fixture"}]}
        elif stage == "refactor":
            result = {"notes": "Fixture states: negative -> -1, nonnegative -> 1.", "files": [{
                "path": "java/src/refactored/java/fixture/Sample.java",
                "content": "package fixture; public class Sample { "
                           "interface SignState { int value(); } "
                           "static class Negative implements SignState { public int value(){return -1;} } "
                           "static class Nonnegative implements SignState { public int value(){return 1;} } "
                           "public int sign(int n) { SignState s; if(n<0) s=new Negative(); "
                           "else s=new Nonnegative(); return s.value(); } }"}]}
        else:
            raise AssertionError(f"Unexpected fixture stage: {stage}")
        return AIMessage(content=json.dumps(result))

    config = {"configurable": {"thread_id": "fixture"}, "recursion_limit": 300}
    value = {}
    for expected_gate in ("review_testcases", "review_refactored", None):
        # Re-open the database between commands, as separate CLI invocations do.
        with SqliteSaver.from_conn_string(str(run.directory / "checkpoints.sqlite")) as saver:
            graph = build_graph(model=RunnableLambda(respond), run=run, checkpointer=saver)
            status = drive(graph, run, value, config)
        if expected_gate is not None:
            assert status["status"] == "waiting_for_human", status.get("error")
            pending = status["pending"][0]
            assert pending["gate"] == expected_gate
            value = Command(resume={"gate": expected_gate, "reviewer": "AUTOMATED TEST FIXTURE",
                                    "timestamp_utc": "2026-11-16T12:00:00Z", "decision": "accept",
                                    "requested_changes": [], "artifact_sha256": pending["artifact_sha256"]})
        else:
            assert status["status"] == "complete", status.get("error")
    for target in ("original", "refactored"):
        assert status["results"][target]["tests"] == 2
        assert status["results"][target]["missed"] == 0
        assert status["results"][target]["covered"] == 2
        assert (run.directory / target / "attempt-1/jacoco.xml").exists()
    assert "complete" in (run.directory / "STATE.md").read_text()
