"""SeasonSwitch JUnit rendering for original and compatible refactored sources.

The project-specific adapter validates vocabulary without inventing expected
outcomes. The generic materializer verifies G1 before adapting targets.
"""
from __future__ import annotations

import json
import re

MARKER = "// Generated by P4 testgen Phase C; do not edit by hand."
STATES = {"OFF", "COOL", "HEAT"}
SETUP_KEYS = {"state", "room.temp", "ac.isOn", "heater.isOn"}
EXPECTED_KEYS = {"state", "ac.isOn", "heater.isOn", "stdout"}
JAVA_ID = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*\Z")


def string_literal(s: str) -> str:
    # Java recognizes JSON's quoting/escaping syntax for these text values.
    return json.dumps(s, ensure_ascii=False)


def state_name(v, label: str) -> str:
    if not isinstance(v, str) or v not in STATES:
        raise ValueError(f"{label} must be OFF, COOL, or HEAT")
    return v


def boolean(v, label: str) -> str:
    if type(v) is not bool:
        raise ValueError(f"{label} must be a JSON boolean")
    return "true" if v else "false"


def integer(v, label: str) -> int:
    if type(v) is not int or not -(2**31) <= v < 2**31:
        raise ValueError(f"{label} must be a 32-bit integer")
    return v


def render(cases: list[dict], profile: dict, class_name: str) -> str:
    if profile.get("project") != "seasonswitch" or profile.get("subject") != "SeasonSwitch":
        raise ValueError("Unexpected SeasonSwitch profile")
    if not JAVA_ID.fullmatch(class_name):
        raise ValueError("Invalid Java class name")
    units = {u["name"]: u for u in profile["units"]}
    supported = {"cool", "heat", "off", "timerOff"}
    if set(units) != supported or any(units[u].get("params") != [] for u in supported):
        raise ValueError("SeasonSwitch adapter only supports its four no-argument public methods")
    if not cases:
        raise ValueError("Test set cannot be empty")
    targets = {case.get("target") for case in cases}
    if len(targets) != 1 or not targets.issubset({"original", "refactored"}):
        raise ValueError("All SeasonSwitch cases must have one supported target")
    lines = [
        MARKER,
        "package cse4392;", "",
        "import static org.junit.jupiter.api.Assertions.*;",
        "import org.junit.jupiter.api.AfterEach;",
        "import org.junit.jupiter.api.BeforeEach;",
        "import org.junit.jupiter.api.DisplayName;",
        "import org.junit.jupiter.api.Test;",
        "import java.io.ByteArrayOutputStream;",
        "import java.io.PrintStream;",
        "import java.nio.charset.StandardCharsets;", "",
        f"class {class_name} {{",
        "    private SeasonSwitch s;", "",
        "    @BeforeEach", "    void setUp() {",
        "        s = new SeasonSwitch();",
        "        s.off(); // Return to OFF through the public API, not by changing state.",
        "        s.timer.stop();", "        s.room.timer.stop();",
        "    }", "",
        "    @AfterEach", "    void tearDown() {",
        "        s.timer.stop();", "        s.room.timer.stop();",
        "        s.off();", "        s.timer.stop();",
        "    }", "",
    ]
    for case in cases:
        # Jordan's State-pattern refactor retains the public methods and compatibility
        # state fields used by these tests. No expected value is rewritten here.
        unit = case["unit"]
        if unit not in supported:
            raise ValueError(f"{case['id']}: unknown unit {unit!r}")
        setup, inputs, expected = case["setup"], case["inputs"], case["expected"]
        if inputs:
            raise ValueError(f"{case['id']}: {unit} has no parameters; inputs must be empty")
        invalid_setup = set(setup) - SETUP_KEYS
        invalid_expected = set(expected) - EXPECTED_KEYS
        if invalid_setup or invalid_expected:
            raise ValueError(f"{case['id']}: unknown fields; setup={sorted(invalid_setup)}, expected={sorted(invalid_expected)}")
        if not expected:
            raise ValueError(f"{case['id']}: at least one expected observation is required")
        state = state_name(setup.get("state", "OFF"), f"{case['id']} setup.state")
        if "state" in expected:
            state_name(expected["state"], f"{case['id']} expected.state")
        for key in ("ac.isOn", "heater.isOn"):
            if key in setup:
                boolean(setup[key], f"{case['id']} setup.{key}")
            if key in expected:
                boolean(expected[key], f"{case['id']} expected.{key}")
        if "room.temp" in setup:
            integer(setup["room.temp"], f"{case['id']} setup.room.temp")
        if "stdout" in expected and not isinstance(expected["stdout"], str):
            raise ValueError(f"{case['id']} expected.stdout must be a string")
        lines.extend([
            "    @Test",
            f"    @DisplayName({string_literal(case['id'] + ' ' + case['partition'])})",
            f"    void test_{case['id'].replace('-', '_')}() {{",
        ])
        if state != "OFF":
            lines.extend([f"        s.{state.lower()}();", "        s.timer.stop();"])
        if "room.temp" in setup:
            lines.append(f"        s.room.temp = {setup['room.temp']};")
        for key in ("ac.isOn", "heater.isOn"):
            if key in setup:
                lines.append(f"        s.{key} = {boolean(setup[key], key)};")
        lines.extend([
            "        ByteArrayOutputStream captured = new ByteArrayOutputStream();",
            "        PrintStream prior = System.out;",
            "        try (PrintStream stream = new PrintStream(captured, true, StandardCharsets.UTF_8)) {",
            "            System.setOut(stream);",
            f"            s.{unit}();",
            "            s.timer.stop(); // Do not let a Swing timer run during assertions.",
            "        } finally {",
            "            System.setOut(prior);",
            "            s.timer.stop();",
            "        }",
        ])
        if "state" in expected:
            lines.append(f"        assertEquals(SeasonSwitch.{expected['state']}, SeasonSwitch.state);")
        for key in ("ac.isOn", "heater.isOn"):
            if key in expected:
                lines.append(f"        assertEquals({boolean(expected[key], key)}, s.{key});")
        if "stdout" in expected:
            # Compare exact expected action output, not invented text based on implementation.
            lines.append("        String actualOutput = captured.toString(StandardCharsets.UTF_8).replace(\"\\r\\n\", \"\\n\");")
            lines.append(f"        assertEquals({string_literal(expected['stdout'])}, actualOutput);")
        lines.extend(["    }", ""])
    lines.append("}")
    return "\n".join(lines) + "\n"
