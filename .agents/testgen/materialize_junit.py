#!/usr/bin/env python3
"""Phase C: turn G1-approved original test cases into JUnit using a project adapter.

This module knows the shared test-case contract, not any project's units or
Java behavior. Project-specific rendering belongs to projects/<project>/junit_adapter.py.
It is a CLI helper; it does not resume LangGraph or approve a human gate.
"""
from __future__ import annotations

import argparse
import importlib.util
from pathlib import Path
import re
import sys
import tempfile
from types import SimpleNamespace

from merge_cases import MergeError, read_json
from review_cases import ReviewError, check as check_g1, review_source

ROOT = Path(__file__).resolve().parents[2]
JAVA_CLASS = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*\Z")
MARKER = "// Generated by P4 testgen Phase C; do not edit by hand."


class MaterializeError(Exception):
    """Cannot safely generate a JUnit source from the supplied artifacts."""


def profile_and_adapter(profile_path: Path):
    """Restrict adapters to the directory of the selected project profile."""
    profile_path = profile_path.resolve()
    project_dir = profile_path.parent
    projects_dir = (ROOT / "projects").resolve()
    if profile_path.name != "profile.json" or project_dir.parent != projects_dir:
        raise MaterializeError("Profile must be projects/<project>/profile.json")
    try:
        profile = read_json(profile_path)
    except MergeError as exc:
        raise MaterializeError(str(exc)) from exc
    if not isinstance(profile, dict) or profile.get("project") != project_dir.name:
        raise MaterializeError("Invalid project profile or mismatched project name")
    adapter_path = project_dir / "junit_adapter.py"
    if not adapter_path.is_file():
        raise MaterializeError(f"No JUnit adapter configured for project {project_dir.name!r}")
    spec = importlib.util.spec_from_file_location("testgen_project_junit_adapter", adapter_path)
    if spec is None or spec.loader is None:
        raise MaterializeError("Unable to load project JUnit adapter")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    if not callable(getattr(module, "render", None)):
        raise MaterializeError("Project JUnit adapter must define render(cases, profile, class_name)")
    return profile, module


def materialize(args: argparse.Namespace) -> Path:
    profile, adapter = profile_and_adapter(args.profile)
    if profile.get("language") != "java":
        raise MaterializeError("Only Java projects can generate JUnit test classes")
    output = args.out.resolve()
    test_root = (ROOT / profile.get("test_root", "")).resolve()
    if test_root == ROOT.resolve() or not test_root.is_relative_to(ROOT.resolve()):
        raise MaterializeError("Invalid test_root in project profile")
    if output.parent != test_root or output.suffix != ".java" or not JAVA_CLASS.fullmatch(output.stem):
        raise MaterializeError("Output must be a Java class immediately inside profile.test_root")
    if output.exists():
        if not output.is_file() or not output.read_text(encoding="utf-8").startswith(MARKER):
            raise MaterializeError("Refusing to overwrite an existing non-generated Java file")
        # A retry must not leave an obsolete passing JUnit source behind.
        output.unlink()
    try:
        cases, _ = review_source(args.cases, args.report)
        check_g1(SimpleNamespace(cases=args.cases, report=args.report, log=args.log))
    except (ReviewError, MergeError) as exc:
        raise MaterializeError(f"G1 approval required: {exc}") from exc
    if cases["target"] != "original":
        raise MaterializeError("Phase C only supports original cases; refactored tests use adapt mode")
    try:
        source = adapter.render(cases["cases"], profile, output.stem)
    except ValueError as exc:
        raise MaterializeError(f"Unsupported test-case vocabulary: {exc}") from exc
    if not isinstance(source, str) or not source.startswith(MARKER):
        raise MaterializeError("Adapter did not produce recognized generated Java source")
    test_root.mkdir(parents=True, exist_ok=True)
    temp_path = None
    try:
        with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=test_root,
                                         prefix=".junit-", suffix=".tmp", delete=False) as file:
            temp_path = Path(file.name)
            file.write(source)
        temp_path.replace(output)
    finally:
        if temp_path is not None:
            temp_path.unlink(missing_ok=True)
    return output


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile", type=Path, required=True)
    parser.add_argument("--cases", type=Path, required=True, help="G1-reviewed testcases_final.json")
    parser.add_argument("--report", type=Path, required=True, help="G1-reviewed dedupe-report.md")
    parser.add_argument("--log", type=Path, required=True, help="human hitl_decisions.json")
    parser.add_argument("--out", type=Path, required=True, help="generated Java file under profile.test_root")
    args = parser.parse_args(argv)
    try:
        output = materialize(args)
    except MaterializeError as exc:
        print(f"PHASE C BLOCKED: {exc}", file=sys.stderr)
        return 1
    print(f"Phase C: wrote G1-approved JUnit tests to {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
